pub fn lgammafn(x: f64) -> f64 {
    lgammafn_sign(x).0
}

pub fn lgammafn_sign(x: f64) -> (f64, i32) {
    if x.is_nan() {
        return (x, 1);
    }
    let sign = if x < 0.0 && ((-x).floor() % 2.0) == 0.0 {
        -1
    } else {
        1
    };
    if x <= 0.0 && x == x.trunc() {
        return (f64::INFINITY, sign);
    }
    let y = x.abs();
    if y < 1e-306 {
        return (-y.ln(), sign);
    }
    if y <= 10.0 {
        return (gammafn(x).abs().ln(), sign);
    }
    if y > 2.532_737_276_080_075_8e305 {
        return (f64::INFINITY, sign);
    }
    if x > 0.0 {
        if x > 1e17 {
            (x * (x.ln() - 1.0), sign)
        } else if x > 4_934_720.0 {
            (M_LN_SQRT_2PI + (x - 0.5) * x.ln() - x, sign)
        } else {
            (M_LN_SQRT_2PI + (x - 0.5) * x.ln() - x + lgammacor(x), sign)
        }
    } else {
        let sinpiy = sinpi(y).abs();
        if sinpiy == 0.0 {
            return (f64::NAN, sign);
        }
        (
            M_LN_SQRT_PI_D2 + (x - 0.5) * y.ln() - x - sinpiy.ln() - lgammacor(y),
            sign,
        )
    }
}

pub fn beta(a: f64, b: f64) -> f64 {
    lbeta(a, b).exp()
}

pub fn lbeta(a: f64, b: f64) -> f64 {
    if a.is_nan() || b.is_nan() {
        return a + b;
    }
    if a <= 0.0 || b <= 0.0 {
        return f64::NAN;
    }
    lgammafn(a) + lgammafn(b) - lgammafn(a + b)
}

pub fn choose(n: f64, k: f64) -> f64 {
    let mut k = force_int(k);
    if n.is_nan() || k.is_nan() {
        return n + k;
    }
    if k < 30.0 {
        if n - k < k && n >= 0.0 && !nonint(n) {
            k = force_int(n - k);
        }
        if k < 0.0 {
            return 0.0;
        }
        if k == 0.0 {
            return 1.0;
        }
        let mut r = n;
        let mut j = 2.0;
        while j <= k {
            r *= (n - j + 1.0) / j;
            j += 1.0;
        }
        return if !nonint(n) { force_int(r) } else { r };
    }
    if n < 0.0 {
        let mut r = choose(-n + k - 1.0, k);
        if k % 2.0 != 0.0 {
            r = -r;
        }
        return r;
    }
    if !nonint(n) {
        let n = force_int(n);
        if n < k {
            return 0.0;
        }
        if n - k < 30.0 {
            return choose(n, n - k);
        }
        return force_int(lchoose(n, k).exp());
    }
    lchoose(n, k).exp()
}

pub fn lchoose(n: f64, k: f64) -> f64 {
    let k = force_int(k);
    if n.is_nan() || k.is_nan() {
        return n + k;
    }
    if k < 2.0 {
        if k < 0.0 {
            return f64::NEG_INFINITY;
        }
        if k == 0.0 {
            return 0.0;
        }
        return n.abs().ln();
    }
    if n < 0.0 {
        return lchoose(-n + k - 1.0, k);
    }
    if !nonint(n) {
        let n = force_int(n);
        if n < k {
            return f64::NEG_INFINITY;
        }
        if n - k < 2.0 {
            return lchoose(n, n - k);
        }
    }
    lgammafn(n + 1.0) - lgammafn(k + 1.0) - lgammafn(n - k + 1.0)
}

