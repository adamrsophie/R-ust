pub(crate) fn bd0(x: f64, np: f64) -> f64 {
    if !x.is_finite() || !np.is_finite() || np == 0.0 {
        return f64::NAN;
    }
    if (x - np).abs() < 0.1 * (x + np) {
        let d = x - np;
        let mut v = d / (x + np);
        if d != 0.0 && v == 0.0 {
            let x_ = x / 4.0;
            let n_ = np / 4.0;
            v = (x_ - n_) / (x_ + n_);
        }
        let mut s = 0.5 * d * v;
        if (2.0 * s).abs() < f64::MIN_POSITIVE {
            return 2.0 * s;
        }
        let mut ej = x * v;
        v *= v;
        for j in 1..1000 {
            ej *= v;
            let old = s;
            s += ej / f64::from((j << 1) + 1);
            if s == old {
                return 2.0 * s;
            }
        }
    }
    let log_ratio = if (x / np).is_finite() {
        (x / np).ln()
    } else {
        x.ln() - np.ln()
    };
    if x > np {
        x * (log_ratio - 1.0) + np
    } else {
        x * log_ratio + np - x
    }
}

fn lgammacor(x: f64) -> f64 {
    const ALGMCS: [f64; 5] = [
        0.1666389480451863247205729650822e+0,
        -0.1384948176067563840732986059135e-4,
        0.9810825646924729426157171547487e-8,
        -0.1809129475572494194263306266719e-10,
        0.6221098041892605227126015543416e-13,
    ];
    if x < 10.0 {
        f64::NAN
    } else if x < 94_906_265.624_251_56 {
        let tmp = 10.0 / x;
        chebyshev_eval(tmp * tmp * 2.0 - 1.0, &ALGMCS) / x
    } else {
        1.0 / (x * 12.0)
    }
}

fn chebyshev_eval(x: f64, coeffs: &[f64]) -> f64 {
    if !(-1.1..=1.1).contains(&x) {
        return f64::NAN;
    }
    let twox = 2.0 * x;
    let mut b2 = 0.0;
    let mut b1 = 0.0;
    let mut b0 = 0.0;
    for coeff in coeffs.iter().rev() {
        b2 = b1;
        b1 = b0;
        b0 = twox * b1 - b2 + coeff;
    }
    0.5 * (b0 - b2)
}
