rows <- vapply(seq_along(cases), function(i) {
  warnings <- character()
  error <- ""
  value <- tryCatch(withCallingHandlers(eval(parse(text=cases[[i]]), new.env(parent=baseenv())),
    warning=function(w) { warnings <<- c(warnings, conditionMessage(w)); invokeRestart("muffleWarning") }),
    error=function(e) { error <<- conditionMessage(e); NULL })
  stopifnot(nzchar(error) || is.integer(value))
  paste(i, cases[[i]], if (nzchar(error)) "error" else "integer",
    if (length(value)) paste(value, collapse=",") else "-",
    if (nzchar(error)) error else "-",
    if (length(warnings)) paste(warnings, collapse="|") else "-", sep="\t")
}, character(1))
writeLines(c(paste0("# ",R.version.string), rows), args[[1]], useBytes=TRUE)
